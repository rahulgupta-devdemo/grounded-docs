"""Answer-quality evaluation through the full question pipeline.

For each answerable question: does the answer contain the expected facts
(regular expressions, all must match) and does it cite a page that holds
the answer? For each unanswerable question: does the answer say clearly
that the documents do not contain the information?

Uses the application's own code end to end (retrieval, prompt, answer
model, citations) with an in-memory Qdrant, so a running instance is not
touched. Calls the answer model once per question.

    cd backend
    .venv/Scripts/python ../evaluation/run_answer_eval.py --docs <folder with the PDFs>
"""

import argparse
import json
import os
import re
import sys
import time
import warnings
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "backend"))
warnings.filterwarnings("ignore", message="Payload indexes have no effect")

from qdrant_client import QdrantClient  # noqa: E402

from app import llm, vector_store  # noqa: E402
from app.answering import answer_question  # noqa: E402
from app.chunking import chunk_pages  # noqa: E402
from app.config import get_settings  # noqa: E402
from app.pdf_parser import extract_pages  # noqa: E402
from app.schemas import DocumentInfo  # noqa: E402

# Phrases the model uses to say the documents do not answer the question.
REFUSAL = re.compile(
    r"(do(es)? not contain|don't contain|not (contain|include|provide|mention)|no information|"
    r"not (found|available|specified|stated)|"
    r"enthalten keine|enthält keine|keine (Informationen|Angaben)|nicht (enthalten|angegeben|erwähnt|genannt))",
    re.IGNORECASE,
)
PAUSE_SECONDS = 2  # stay well below the free-tier requests-per-minute limit


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--docs", type=Path, required=True)
    parser.add_argument("--questions", type=Path, default=HERE / "questions.json")
    parser.add_argument("--out", type=Path, default=HERE / "results_answers.md")
    parser.add_argument("--mode", choices=["hybrid", "dense"], help="override RETRIEVAL_MODE")
    args = parser.parse_args()
    if args.mode:
        os.environ["RETRIEVAL_MODE"] = args.mode
        get_settings.cache_clear()

    spec = json.loads(args.questions.read_text(encoding="utf-8"))
    files = spec["documents"]
    index_documents(args.docs, files)

    rows, facts_ok, pages_ok = [], 0, 0
    answerable = [q for q in spec["questions"] if "answer" in q]
    for q in answerable:
        response = ask(q["q"])
        expected = {(files[alias], page) for alias, page in q["expected"]}
        cited = {(s.filename, s.page) for s in response.sources if s.cited}
        fact = all(re.search(p, response.answer, re.IGNORECASE | re.DOTALL) for p in q["answer"])
        page = bool(cited & expected)
        facts_ok += fact
        pages_ok += page
        rows.append((q["q"], fact, page, response.answer))
        print(f"{'OK' if fact else '--'} fact  {'OK' if page else '--'} page  {q['q']}")

    refusal_rows, refusals_ok = [], 0
    for question in spec.get("unanswerable", []):
        response = ask(question)
        refused = REFUSAL.search(response.answer) is not None
        refusals_ok += refused
        refusal_rows.append((question, refused, response.answer))
        print(f"{'OK' if refused else '--'} refusal  {question}")

    summary = (
        f"Answerable: {facts_ok}/{len(answerable)} answers contain the expected facts, "
        f"{pages_ok}/{len(answerable)} cite a page that holds the answer. "
        f"Unanswerable: {refusals_ok}/{len(refusal_rows)} correctly say the documents do not contain it."
    )
    print("\n" + summary)
    args.out.write_text(build_report(summary, rows, refusal_rows), encoding="utf-8", newline="\n")
    print(f"Written to {args.out}")


def index_documents(docs: Path, files: dict[str, str]) -> None:
    settings = get_settings()
    client = QdrantClient(":memory:")
    vector_store.get_client = lambda: client
    for i, name in enumerate(files.values()):
        pages = extract_pages((docs / name).read_bytes())
        chunks = chunk_pages(pages, settings.chunk_size, settings.chunk_overlap)
        document = DocumentInfo(id=f"{i:016x}", filename=name, pages=len(pages), chunks=len(chunks))
        vector_store.replace_document(document, chunks, llm.embed_documents([(name, c.text) for c in chunks]))


def ask(question: str):
    response = answer_question(question)
    time.sleep(PAUSE_SECONDS)
    return response


def build_report(summary, rows, refusal_rows) -> str:
    settings = get_settings()
    lines = [
        "# Answer-quality evaluation",
        "",
        summary,
        "",
        f"Search: {settings.retrieval_mode}. Chunking {settings.chunk_size}/{settings.chunk_overlap}, "
        f"top {settings.top_k} passages, answer models {settings.chat_models}. "
        "Generated by `evaluation/run_answer_eval.py`.",
        "",
        "## Answerable questions",
        "",
        "| Question | Facts | Page cited | Answer |",
        "|---|---|---|---|",
    ]
    for question, fact, page, answer in rows:
        lines.append(f"| {question} | {'yes' if fact else 'NO'} | {'yes' if page else 'NO'} | {one_line(answer)} |")
    lines += ["", "## Unanswerable questions", "", "| Question | Refused | Answer |", "|---|---|---|"]
    for question, refused, answer in refusal_rows:
        lines.append(f"| {question} | {'yes' if refused else 'NO'} | {one_line(answer)} |")
    return "\n".join(lines) + "\n"


def one_line(text: str) -> str:
    return text.replace("\n", " ").replace("|", "/")[:220]


if __name__ == "__main__":
    main()
