"""Retrieval evaluation: for each question, is a page that holds the answer
among the retrieved passages, and how high is it ranked?

Uses the application's own parsing, chunking, embedding and search code with
an in-memory Qdrant, so the running app's data is not touched. Only
embeddings are called, no answer model.

    cd backend
    .venv/Scripts/python ../evaluation/run_eval.py --docs <folder with the PDFs>
"""

import argparse
import json
import sys
import time
import warnings
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "backend"))
warnings.filterwarnings("ignore", message="Payload indexes have no effect")

from qdrant_client import QdrantClient  # noqa: E402

from app import llm, vector_store  # noqa: E402
from app.chunking import chunk_pages  # noqa: E402
from app.language import detect_language  # noqa: E402
from app.pdf_parser import extract_pages  # noqa: E402
from app.schemas import DocumentInfo  # noqa: E402

CHUNK_CONFIGS = [(800, 100), (1500, 200), (3000, 400)]  # (size, overlap) in characters
DEFAULT_CONFIG = (1500, 200)
K = 5


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--docs", type=Path, required=True)
    parser.add_argument("--questions", type=Path, default=HERE / "questions.json")
    parser.add_argument("--out", type=Path, default=HERE / "results.md")
    args = parser.parse_args()

    spec = json.loads(args.questions.read_text(encoding="utf-8"))
    files = spec["documents"]
    questions = [
        {"q": q["q"], "expected": {(files[alias], page) for alias, page in q["expected"]}}
        for q in spec["questions"]
    ]
    pages = {name: extract_pages((args.docs / name).read_bytes()) for name in files.values()}

    print(f"Embedding {len(questions)} questions ...")
    query_vectors = {q["q"]: llm.embed_query(q["q"]) for q in questions}

    runs = []
    for i, (size, overlap) in enumerate(CHUNK_CONFIGS):
        if i > 0:
            # The free tier allows 100 embedded texts per minute.
            print("Waiting 60 s for the embedding quota ...")
            time.sleep(60)
        chunk_count = index_documents(pages, size, overlap)
        ranks = [rank_of_answer(query_vectors[q["q"]], q["expected"]) for q in questions]
        runs.append({"size": size, "overlap": overlap, "chunks": chunk_count, "ranks": ranks})
        print(f"size {size:>4} / overlap {overlap:>3}: {format_metrics(metrics(ranks))}")

    report = build_report(questions, runs)
    args.out.write_text(report, encoding="utf-8")
    print(f"\nWritten to {args.out}")


def index_documents(pages: dict, size: int, overlap: int) -> int:
    client = QdrantClient(":memory:")
    vector_store.get_client = lambda: client
    total = 0
    for i, (name, document_pages) in enumerate(pages.items()):
        chunks = chunk_pages(document_pages, size, overlap)
        document = DocumentInfo(id=f"{i:016x}", filename=name, pages=len(document_pages), chunks=len(chunks))
        vectors = llm.embed_documents([(name, chunk.text) for chunk in chunks])
        vector_store.replace_document(document, chunks, vectors)
        total += len(chunks)
    return total


def rank_of_answer(vector: list[float], expected: set[tuple[str, int]]) -> int | None:
    hits = vector_store.search(vector, limit=K)
    return next(
        (rank for rank, hit in enumerate(hits, start=1) if (hit.filename, hit.page) in expected),
        None,
    )


def metrics(ranks: list[int | None]) -> dict[str, float]:
    n = len(ranks)
    return {
        "hit@1": sum(r is not None and r <= 1 for r in ranks) / n,
        "hit@3": sum(r is not None and r <= 3 for r in ranks) / n,
        "hit@5": sum(r is not None and r <= 5 for r in ranks) / n,
        "MRR": sum(1 / r for r in ranks if r is not None) / n,
    }


def format_metrics(m: dict[str, float]) -> str:
    return "  ".join(f"{name} {value:.2f}" for name, value in m.items())


def build_report(questions: list[dict], runs: list[dict]) -> str:
    lines = [
        "# Retrieval evaluation",
        "",
        f"{len(questions)} questions ({sum(detect_language(q['q']) == 'German' for q in questions)} German, "
        f"{sum(detect_language(q['q']) == 'English' for q in questions)} English) on four public product documents: "
        "a product brochure in German and English, and two datasheets "
        "(one English, one German). A question counts as answered at rank r if a passage from a page that "
        f"holds the answer is at position r of the top {K}. Generated by `evaluation/run_eval.py`.",
        "",
        "| Chunk size / overlap (characters) | Passages | hit@1 | hit@3 | hit@5 | MRR |",
        "|---|---|---|---|---|---|",
    ]
    for run in runs:
        m = metrics(run["ranks"])
        marker = " (default)" if (run["size"], run["overlap"]) == DEFAULT_CONFIG else ""
        lines.append(
            f"| {run['size']} / {run['overlap']}{marker} | {run['chunks']} | "
            f"{m['hit@1']:.2f} | {m['hit@3']:.2f} | {m['hit@5']:.2f} | {m['MRR']:.2f} |"
        )

    default = next(r for r in runs if (r["size"], r["overlap"]) == DEFAULT_CONFIG)
    lines += ["", "## By question language (default chunking)", "", "| Language | Questions | hit@1 | hit@5 | MRR |", "|---|---|---|---|---|"]
    for language in ("German", "English"):
        ranks = [r for q, r in zip(questions, default["ranks"]) if detect_language(q["q"]) == language]
        m = metrics(ranks)
        lines.append(f"| {language} | {len(ranks)} | {m['hit@1']:.2f} | {m['hit@5']:.2f} | {m['MRR']:.2f} |")

    lines += ["", "## Per question (default chunking)", "", "| Question | Rank of first correct page |", "|---|---|"]
    for q, rank in zip(questions, default["ranks"]):
        lines.append(f"| {q['q']} | {rank if rank is not None else 'not in top ' + str(K)} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    main()
